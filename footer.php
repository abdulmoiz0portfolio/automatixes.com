    <script>
        function initExpertModal() {
            const stickyBtn = document.getElementById('sticky-expert-btn');
            const modal = document.getElementById('expertConnectModal');
            const closeBtn = document.getElementById('closeExpertModal');
            const scrollBtn = document.getElementById('expertScrollToContact');
            const quickForm = document.getElementById('expertQuickForm');
            const successMsg = document.getElementById('expertFormSuccess');

            if (!stickyBtn || !modal) return;

            function openModal(e) {
                if (e && e.preventDefault) e.preventDefault();
                modal.style.display = 'flex';
                requestAnimationFrame(() => {
                    modal.classList.add('active');
                });
            }

            function closeModal() {
                modal.classList.remove('active');
                setTimeout(() => {
                    modal.style.display = 'none';
                }, 300);
            }

            stickyBtn.addEventListener('click', openModal);

            if (closeBtn) {
                closeBtn.addEventListener('click', closeModal);
            }

            modal.addEventListener('click', (e) => {
                if (e.target === modal) closeModal();
            });

            document.addEventListener('keydown', (e) => {
                if (e.key === 'Escape' && modal.classList.contains('active')) {
                    closeModal();
                }
            });

            if (scrollBtn) {
                scrollBtn.addEventListener('click', (e) => {
                    const contactSec = document.getElementById('contact-section');
                    if (contactSec) {
                        e.preventDefault();
                        closeModal();
                        setTimeout(() => {
                            if (window.lenis) {
                                window.lenis.scrollTo(contactSec, { offset: -50, duration: 1.2 });
                            } else {
                                contactSec.scrollIntoView({ behavior: 'smooth' });
                            }
                            const nameInp = document.getElementById('contact-name') || document.querySelector('#contact-section input');
                            if (nameInp) setTimeout(() => nameInp.focus(), 600);
                        }, 350);
                    }
                });
            }

            if (quickForm) {
                quickForm.addEventListener('submit', (e) => {
                    e.preventDefault();
                    const name = document.getElementById('expertName').value.trim();
                    const contact = document.getElementById('expertContact').value.trim();
                    if (!name || !contact) return;

                    const waUrl = `https://wa.me/923366920141?text=${encodeURIComponent(`Hi Automatixes! My name is ${name} (${contact}). I want to connect with an automation expert for my business.`)}`;
                    if (successMsg) successMsg.style.display = 'block';
                    setTimeout(() => {
                        window.open(waUrl, '_blank');
                        closeModal();
                    }, 800);
                });
            }

            window.connectWithExpert = openModal;
        }

        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', initExpertModal);
        } else {
            initExpertModal();
        }
    </script>



